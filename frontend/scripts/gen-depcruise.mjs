// TX25: dependency-cruiser rules generated from the G03.3 coupling table of the SSOT architecture package.
// `--check` fails on drift between the table and .dependency-cruiser.cjs (E-10: generated output is never edited).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "..");
const doc = resolve(app, "../docs/architecture/SYNTX_CIRA_Consolidated_Architecture_Package_v1.0.2.md");
const out = resolve(app, ".dependency-cruiser.cjs");

const FOLDER = { Session: "session", Access: "access", Provenance: "provenance", Semiontic: "semiontics", Language: "language",
  Shell: "shell", Views: "views", Time: "time", Control: "control", Demo: "demo" };

const md = readFileSync(doc, "utf-8");
const start = md.indexOf("### G03.3");
const table = md.slice(start, md.indexOf("\n### ", start + 10)).split("\n").filter((l) => l.startsWith("| ") && !l.startsWith("|---"));
const header = table[0].split("|").slice(2, -1).map((c) => c.trim().replace(/^\d+\s+/, "").replace(/\.$/, ""));
const cols = header.map((h) => Object.keys(FOLDER).find((k) => k.startsWith(h)) ?? h);
const allowed = {};
for (const row of table.slice(1)) {
  const cells = row.split("|").slice(1, -1).map((c) => c.trim());
  const from = Object.keys(FOLDER).find((k) => cells[0].replace(/^\d+\s+/, "").startsWith(k));
  if (!from) throw new Error(`unparsed row: ${row}`);
  allowed[from] = cols.filter((_, i) => cells[i + 1] === "R");
}
if (Object.keys(allowed).length !== 10) throw new Error(`expected 10 sub-fields, got ${Object.keys(allowed).length}`);

const rules = [];
for (const from of Object.keys(FOLDER)) {
  const forbidden = Object.keys(FOLDER).filter((to) => to !== from && !allowed[from].includes(to));
  if (!forbidden.length) continue;
  rules.push({ name: `g03-3-${FOLDER[from]}`, severity: "error", comment: `${from} may import only: ${allowed[from].join(", ") || "nothing"} (G03.3)`,
    from: { path: `^src/${FOLDER[from]}/` }, to: { path: `^src/(${forbidden.map((t) => FOLDER[t]).join("|")})/` } });
}
rules.push({ name: "g03-3-contracts", severity: "error",
  comment: "contracts/generated only from Access, Provenance and ViewModel files in Views (G03.3)",
  from: { path: "^src/", pathNot: "^src/(access|provenance|contracts)/|^src/views/[^/]+/model\\.ts$" },
  to: { path: "^src/contracts/generated/" } });
rules.push({ name: "g03-3-primitives-no-contracts", severity: "error", comment: "Primitives know SEM ids and values only (G03.3)",
  from: { path: "^src/semiontics/" }, to: { path: "^src/(contracts|access)/" } });
rules.push({ name: "views-not-other-views", severity: "error", comment: "a view module imports only its own folder and views/_common (G03.3 Views ↛ Views)",
  from: { path: "^src/views/([^/_][^/]*)/" }, to: { path: "^src/views/", pathNot: ["^src/views/$1/", "^src/views/_common/"] } });
rules.push({ name: "no-circular", severity: "error", from: {}, to: { circular: true } });

const body = `/* GENERATED by scripts/gen-depcruise.mjs from G03.3 (${"SYNTX_CIRA_Consolidated_Architecture_Package_v1.0.2.md"}) — do not edit (E-10, TX25) */
module.exports = ${JSON.stringify({ forbidden: rules, options: { doNotFollow: { path: "node_modules|src/contracts/generated" }, tsPreCompilationDeps: true,
  tsConfig: { fileName: "tsconfig.json" }, exclude: { path: "\\.test\\.tsx?$" } } }, null, 2)};
`;
if (process.argv.includes("--check")) {
  const same = existsSync(out) && readFileSync(out, "utf-8") === body;
  console.log(same ? "depcruise rules: in sync with G03.3" : "depcruise rules: DRIFT against G03.3");
  process.exit(same ? 0 : 1);
}
writeFileSync(out, body);
console.log(`wrote .dependency-cruiser.cjs (${rules.length} rules) from G03.3`);
