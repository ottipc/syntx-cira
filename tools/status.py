#!/usr/bin/env python3
"""Compute docs/STATUS.md from registry.yaml + the latest machine report (15.7, K-51, K-73). Never hand-edited."""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import ROOT, latest_report, min_phase, registry  # noqa: E402

OUT = ROOT / "docs" / "STATUS.md"


def _py_files(c: str) -> list[Path]:
    p = ROOT / c
    if p.is_dir():
        return sorted(p.rglob("*.py"))
    return [p] if p.suffix == ".py" else []


def req_states(reg: dict[str, Any], rep: dict[str, Any] | None) -> list[dict[str, Any]]:
    cur = int(reg["current_phase"])
    gates = reg.get("phase_tests", {})
    tests = (rep or {}).get("tests", {})
    by_tid: dict[str, list[str]] = {}
    by_req: dict[str, list[str]] = {}
    for nodeid, t in tests.items():
        for x in t["tids"]:
            by_tid.setdefault(x, []).append(t["outcome"])
        for x in t["reqs"]:
            by_req.setdefault(x, []).append(t["outcome"])
    mypy_ok = any(s["name"] == "mypy" and s["status"] == "passed" for s in (rep or {}).get("suites", []))
    icov: dict[str, float] = (rep or {}).get("integration_coverage", {})
    open_deps = {d["id"] for d in reg["dependencies"] if d["state"] == "OPEN"}
    out = []
    for r in reg["requirements"]:
        st: dict[str, Any] = {"id": r["id"], "title": r["title"], "phase": r["phase"], "arch": r["arch_state"]}
        if r["arch_state"] != "ACCEPTED":
            st["status"] = r["arch_state"]
            out.append(st)
            continue
        if r["kind"] == "process":
            st["status"] = "PROCESS"
            out.append(st)
            continue
        missing = [c for c in r["components"] if not (ROOT / c).exists()]
        stubs = [str(p.relative_to(ROOT)) for c in r["components"] for p in _py_files(c)
                 if p.exists() and re.search(r"raise NotImplementedError", p.read_text(encoding="utf-8"))]
        implemented = not missing and not stubs and mypy_ok and bool(r["components"])
        pyfiles = [str(p.relative_to(ROOT)) for c in r["components"] for p in _py_files(c) if p.exists()]
        if r.get("integration") == "not_applicable":
            integrated = implemented  # build-time or test asset; nothing to reach at runtime (registry note)
        elif not pyfiles:
            integrated = implemented and bool(icov)  # data/config components consumed by the integrated runtime
        else:
            integrated = implemented and all(icov.get(f, 0.0) > 0 for f in pyfiles)
        gate = {x for p in range(1, 6) for x in gates.get(f"{p:02d}", [])}
        outcomes = list(by_req.get(r["id"], [])) + [o for t in r["tests"] if t in gate for o in by_tid.get(t, [])]
        unmet = [t for t in r["tests"] if t in gate and not by_tid.get(t)]
        tests_green = bool(outcomes) and all(o == "passed" for o in outcomes) and not unmet
        st.update(missing=missing, stubs=stubs, tests_green=tests_green, unmet_tests=unmet,
                  n_tests=len(outcomes), integrated=integrated, integration_note=r.get("integration_note"))
        if implemented and integrated and tests_green:
            status = "VERIFIED"
        elif implemented and integrated:
            status = "INTEGRATED"
        elif implemented:
            status = "IMPLEMENTED"
        else:
            status = "DESIGNED"
        deps = [d for d in r.get("deps", []) if d in open_deps]
        if deps:
            st["blocked_by"] = deps
            status = "BLOCKED_DEP"
        st["status"] = status
        st["due"] = (min_phase(r["phase"]) or 99) <= cur
        out.append(st)
    return out


def coverage_summary(states: list[dict[str, Any]]) -> dict[str, list[str]]:
    res: dict[str, list[str]] = {}
    for s in states:
        res.setdefault(s["status"], []).append(s["id"])
    return res


def render() -> str:
    reg = registry()
    lr = latest_report()
    rep = lr[1] if lr else None
    states = req_states(reg, rep)
    summ = coverage_summary(states)
    L = ["# CIRA — STATUS (computed)", "",
         "> Generated by `make status` (tools/status.py) from `docs/traceability/registry.yaml` and the latest",
         "> machine report. Do not edit by hand (E-10, 15.6).", ""]
    L += [f"- Architecture: FROZEN v{reg['version']} · gate_mode `{reg['gate_mode']}` · current phase **{reg['current_phase']}**"]
    if rep:
        g = rep["gate"]
        L += [f"- Latest report: `{lr[0].relative_to(ROOT)}` · phase {rep['phase']} · commit `{rep['commit']}`",
              f"- Report hash: `{rep['hash']}`",
              f"- Gate {rep['phase']}: **{'PASSED' if g['passed'] else 'NOT PASSED'}** — "
              + ", ".join(f"{k}={'ok' if v else 'FAIL'}" for k, v in g["conditions"].items()),
              f"- Tests: {rep['totals']['passed']} passed · {rep['totals']['failed']} failed · "
              f"{rep['totals']['skipped']} skipped"]
    else:
        L += ["- Latest report: none"]
    L += ["", "## Requirement status ladder (15.7)", "",
          "| Status | Count |", "|---|---|"]
    for k in ("VERIFIED", "INTEGRATED", "IMPLEMENTED", "DESIGNED", "BLOCKED_DEP", "PROVISIONAL", "PROCESS"):
        L.append(f"| {k} | {len(summ.get(k, []))} |")
    L += ["", "| REQ | Phase | Status | Tests green | Notes |", "|---|---|---|---|---|"]
    for s in states:
        notes = []
        if s.get("blocked_by"):
            notes.append("blocked by " + ", ".join(s["blocked_by"]))
        if s.get("missing"):
            notes.append(f"{len(s['missing'])} component(s) not yet present")
        if s.get("stubs"):
            notes.append("port stub (NotImplementedError)")
        if s.get("integration_note"):
            notes.append("integration n/a: " + s["integration_note"])
        if s.get("unmet_tests"):
            notes.append("tests pending: " + ", ".join(s["unmet_tests"]))
        if s["status"] == "IMPLEMENTED" and not s.get("integrated"):
            notes.append("integration coverage pending")
        tg = "—" if "tests_green" not in s else ("yes" if s["tests_green"] else "no")
        L.append(f"| {s['id']} | {s['phase']} | {s['status']} | {tg} | {'; '.join(notes)} |")
    L += ["", "## Gate tests per phase", "", "| Phase | Tests | Result |", "|---|---|---|"]
    tid_out: dict[str, list[str]] = {}
    for t in (rep or {}).get("tests", {}).values():
        for x in t["tids"]:
            tid_out.setdefault(x, []).append(t["outcome"])
    for p, tids in reg["phase_tests"].items():
        res = []
        for t in tids:
            o = tid_out.get(t)
            res.append(f"{t}:{'—' if not o else ('ok' if all(x == 'passed' for x in o) else 'FAIL')}")
        L.append(f"| {p} | {len(tids)} | {' '.join(res)} |")
    L += ["", "## External dependencies (E-18)", "", "| DEP | State | Note |", "|---|---|---|"]
    for d in reg["dependencies"]:
        L.append(f"| {d['id']} | {d['state']} | {d.get('note', '')} |")
    L += ["", "## Review points and proposals (K-73)", "",
          "All RV-01–RV-07, RV-GUI-01–RV-GUI-11 and all proposals K-58–K-76, GK-01–GK-29, D-40–D-49, A-14, X-28–X-33,",
          "SEM-031–SEM-036 are ACCEPTED (docs/architecture/ARCHITECTURE_FREEZE_v1.0.2.md). Open review points: none.", ""]
    if rep and rep.get("ak_status"):
        L += ["## Acceptance (AK)", "", "| AK | Status | Evidence |", "|---|---|---|"]
        for a in rep["ak_status"]:
            L.append(f"| {a['id']} | {a['status']} | {a.get('evidence', '')} |")
        L.append("")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("STATUS.md: in sync" if ok else "STATUS.md: DRIFT")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
