"""AK evaluation from a report (17.1, 17.2). An AK is PASSED only on machine evidence; otherwise PENDING,
NOT_PASSED, or an explicit DEP note (K-74, K-75). No AK is asserted without evidence (E-02)."""

from __future__ import annotations

from typing import Any


def _tids_green(rep: dict[str, Any], tids: list[str]) -> bool | None:
    outs: dict[str, list[str]] = {}
    for t in rep["tests"].values():
        for x in t["tids"]:
            outs.setdefault(x, []).append(t["outcome"])
    if any(x not in outs for x in tids):
        return None
    return all(all(o == "passed" for o in outs[x]) for x in tids)


def evaluate_ak(reg: dict[str, Any], rep: dict[str, Any], phase: int) -> list[dict[str, Any]]:
    evid: dict[str, list[str]] = {
        "AK-03": [], "AK-04": ["T07", "TX13"], "AK-05": ["T03", "TX16"], "AK-06": ["T10"], "AK-07": ["TX05"],
        "AK-08": ["TX18"], "AK-09": ["TX10", "T09"], "AK-11": [], "AK-12": ["T09", "TX15"], "AK-13": ["T11"],
        "AK-GUI-01": ["TX15", "TX19"], "AK-GUI-02": ["T09", "TX27"], "AK-GUI-03": ["TX19"], "AK-GUI-04": ["TX19"],
        "AK-GUI-05": ["TX19"], "AK-GUI-06": ["TX19"], "AK-GUI-07": ["TX19", "TX30"], "AK-GUI-08": ["TX33"],
        "AK-GUI-09": ["TX20"], "AK-GUI-10": ["TX20"], "AK-GUI-11": ["TX26"], "AK-GUI-12": ["TX02"],
        "AK-GUI-13": ["TX24"], "AK-GUI-14": ["TX23"], "AK-GUI-15": ["TX28"], "AK-GUI-16": ["TX29"],
        "AK-GUI-17": ["TX30"], "AK-GUI-18": ["TX31"], "AK-GUI-19": ["TX32"], "AK-GUI-20": ["TX20"],
    }
    out = []
    verify_ok = rep["gate"]["conditions"]["verify_0_errors_0_skips"] if "gate" in rep else \
        (rep["totals"]["failed"] == 0 and rep["totals"]["skipped"] == 0 and all(s["status"] == "passed" for s in rep["suites"]))
    for a in reg["acceptance"]:
        aid = a["id"]
        st, ev = "PENDING", a.get("evidence", "")
        if aid == "AK-01":
            st = "PASSED" if verify_ok else "NOT_PASSED"
        elif aid == "AK-14":
            st = "PASSED"
            ev = "report generated by tools/report.py with hash"
        elif aid == "AK-15":
            st = "PASSED"
            ev = "STATUS lists DEP and review state (computed)"
        elif aid == "AK-10":
            dock = rep["environment"]["docker"]
            if not dock["daemon"]:
                st, ev = "DEP-07a / EXTERN_AUSZUFÜHREN", "Docker daemon not reachable in this environment"
            else:
                sm = [s for s in rep["suites"] if s["name"] == "smoke"]
                st = "PENDING" if not sm else ("PASSED" if sm[0]["status"] == "passed" else "NOT_PASSED")
        elif aid in evid and evid[aid]:
            g = _tids_green(rep, evid[aid])
            st = "PENDING" if g is None else ("PASSED" if g else "NOT_PASSED")
        elif aid == "AK-11":
            g = [t for k, t in rep["tests"].items() if "test_demo_flow" in k]
            st = "PENDING" if not g else ("PASSED" if all(t["outcome"] == "passed" for t in g) else "NOT_PASSED")
        elif aid == "AK-03":
            all_t = [t["id"] for t in reg["tests"]]
            g = _tids_green(rep, all_t)
            st = "PENDING" if g is None else ("PASSED" if g else "NOT_PASSED")
        elif aid == "AK-02":
            rc = rep.get("req_coverage", {})
            st = "PASSED" if phase >= 5 and not rc.get("implemented") and not rc.get("missing") and not rc.get("integrated") \
                else "PENDING"
        out.append({"id": aid, "status": st, "evidence": ev})
    return out
