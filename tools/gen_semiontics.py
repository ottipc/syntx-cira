# ---- minimal JSON-schema subset validator (type, required, properties, items, enum, pattern) --------------------
def validate(inst: Any, schema: dict[str, Any], path: str = "$") -> list[str]:
    errs: list[str] = []
    t = schema.get("type")
    types = {"object": dict, "array": list, "string": str, "integer": int, "number": (int, float), "boolean": bool}
    if t and not isinstance(inst, types[t]):  # type: ignore[arg-type]
        return [f"{path}: expected {t}"]
    if "enum" in schema and inst not in schema["enum"]:
        errs.append(f"{path}: {inst!r} not in {schema['enum']}")
    if "pattern" in schema and isinstance(inst, str) and not re.match(schema["pattern"], inst):
        errs.append(f"{path}: {inst!r} does not match {schema['pattern']}")
    if isinstance(inst, dict):
        for r in schema.get("required", []):
            if r not in inst:
                errs.append(f"{path}: missing {r}")
        for k, s in schema.get("properties", {}).items():
            if k in inst:
                errs += validate(inst[k], s, f"{path}.{k}")
    if isinstance(inst, list) and "items" in schema:
        for i, x in enumerate(inst):
            errs += validate(x, schema["items"], f"{path}[{i}]")
    return errs


# ---- colour science (WCAG 2.x contrast, CIEDE2000) --------------------------------------------------------------
def _rgb(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]


def _lin(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(h: str) -> float:
    r, g, b = (_lin(x) for x in _rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def _lab(h: str) -> tuple[float, float, float]:
    r, g, b = (_lin(x) for x in _rgb(h))
    x = (0.4124564 * r + 0.3575761 * g + 0.1804375 * b) / 0.95047
    y = (0.2126729 * r + 0.7151522 * g + 0.0721750 * b) / 1.0
    z = (0.0193339 * r + 0.1191920 * g + 0.9503041 * b) / 1.08883

    def f(t: float) -> float:
        return t ** (1 / 3) if t > 216 / 24389 else (24389 / 27 * t + 16) / 116
    fx, fy, fz = f(x), f(y), f(z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def ciede2000(c1: str, c2: str) -> float:
    L1, a1, b1 = _lab(c1)
    L2, a2, b2 = _lab(c2)
    C1, C2 = math.hypot(a1, b1), math.hypot(a2, b2)
    Cm = (C1 + C2) / 2
    G = 0.5 * (1 - math.sqrt(Cm ** 7 / (Cm ** 7 + 25 ** 7)))
    a1p, a2p = (1 + G) * a1, (1 + G) * a2
    C1p, C2p = math.hypot(a1p, b1), math.hypot(a2p, b2)
    h1p = math.degrees(math.atan2(b1, a1p)) % 360
    h2p = math.degrees(math.atan2(b2, a2p)) % 360
    dLp, dCp = L2 - L1, C2p - C1p
    dhp = 0.0 if C1p * C2p == 0 else (h2p - h1p if abs(h2p - h1p) <= 180 else
                                       h2p - h1p - 360 if h2p - h1p > 180 else h2p - h1p + 360)
    dHp = 2 * math.sqrt(C1p * C2p) * math.sin(math.radians(dhp / 2))
    Lpm, Cpm = (L1 + L2) / 2, (C1p + C2p) / 2
    if C1p * C2p == 0:
        hpm = h1p + h2p
    elif abs(h1p - h2p) <= 180:
        hpm = (h1p + h2p) / 2
    else:
        hpm = (h1p + h2p + 360) / 2 if h1p + h2p < 360 else (h1p + h2p - 360) / 2
    T = (1 - 0.17 * math.cos(math.radians(hpm - 30)) + 0.24 * math.cos(math.radians(2 * hpm))
         + 0.32 * math.cos(math.radians(3 * hpm + 6)) - 0.20 * math.cos(math.radians(4 * hpm - 63)))
    dth = 30 * math.exp(-(((hpm - 275) / 25) ** 2))
    Rc = 2 * math.sqrt(Cpm ** 7 / (Cpm ** 7 + 25 ** 7))
    Sl = 1 + 0.015 * (Lpm - 50) ** 2 / math.sqrt(20 + (Lpm - 50) ** 2)
    Sc, Sh = 1 + 0.045 * Cpm, 1 + 0.015 * Cpm * T
    Rt = -math.sin(math.radians(2 * dth)) * Rc
    return math.sqrt((dLp / Sl) ** 2 + (dCp / Sc) ** 2 + (dHp / Sh) ** 2 + Rt * (dCp / Sc) * (dHp / Sh))


def _mix(a: str, b: str, t: float) -> str:
    """sRGB 8-bit mix t·a + (1−t)·b, rounded half to even (declared rounding of derived tokens)."""
    A, B = _rgb(a), _rgb(b)
    return "#" + "".join(f"{round((A[i] * t + B[i] * (1 - t)) * 255):02X}" for i in range(3))


def resolve(tok: dict[str, Any]) -> dict[str, str]:
    """Colour table including derived tokens (v1.1.0 `derive`, architecture v2.0.3 05.1 T1)."""
    col = dict(tok["color"])
    for k, d in tok.get("derive", {}).items():
        if d["op"] == "mix":
            col[k] = _mix(col[d["a"]], col[d["b"]], float(d["t"]))
        elif d["op"] == "lightest_on_path":
            best = col[d["from"]]
            for i in range(1001):
                c = _mix(col[d["to"]], col[d["from"]], i / 1000)
                if all(contrast(col[f], c) >= m for f, m in d["keep"].items()):
                    best = c
            col[k] = best
        else:
            raise SystemExit(f"gen_semiontics: unknown derive op {d['op']}")
    return col


def neuro_report(tok: dict[str, Any], col: dict[str, str]) -> tuple[dict[str, Any], list[str]]:
    """v1.1.0 checks: focus/attenuated grounds, transition path minima, decor budgets, graphic inks, projector profile."""
    rules, out, errs = tok["contrast_rules"], {}, []
    if "derive" not in tok:
        return out, errs
    tmin, gmin = rules["text_min"], rules["graphic_min"]
    texts = rules["text_tokens"] + rules["text_tokens_field_panel"]
    out["focus"] = {t: round(contrast(col[t], col["surface.focus"]), 2) for t in texts}
    out["transitions"] = {}
    for name, (f0, f1, b0, b1) in tok.get("transitions", {}).items():
        m = min(contrast(_mix(col[f1], col[f0], i / 200), _mix(col[b1], col[b0], i / 200)) for i in range(201))
        out["transitions"][name] = round(m, 4)
        if m < tmin:
            errs.append(f"V3T01: transition {name} minimum {m:.2f} < {tmin}")
    dr, dec = tok["decor_rules"], tok["decor"]
    out["decor"] = {}
    for key in ("alpha.text", "axis.alpha"):
        g = _mix(col["brand.core"], col[dr["ground"]], float(dec[key]))
        for t in dr["text_on_decor"]:
            c = contrast(col[t], g)
            out["decor"][f"{t} @ {key}"] = round(c, 2)
            if c < tmin:
                errs.append(f"V3T01: {t} on decor ({key}) = {c:.2f}")
    for t in dr["excluded_from_decor_ground"]:
        out["decor"][f"{t} @ alpha.text (excluded)"] = round(contrast(col[t], _mix(col["brand.core"], col[dr["ground"]], float(dec["alpha.text"]))), 2)
    for t in list(out["focus"]):
        if out["focus"][t] < tmin:
            errs.append(f"V3T01: {t} on surface.focus = {out['focus'][t]}")
    surfaces = ["surface.void", "surface.field", "surface.panel", "surface.focus", "surface.elevated"]
    for g_ in dr["graphic_inks"]:
        for s_ in surfaces:
            if contrast(col[g_], col[s_]) < gmin:
                errs.append(f"V3T01: graphic {g_} on {s_} < {gmin}")
    p = {**col, **{k: v for k, v in tok.get("profile_projector", {}).items() if isinstance(v, str) and v.startswith("#")}}
    out["projector"] = {"edge": {s_: round(contrast(p["border.strong"], p[s_]), 3) for s_ in surfaces}, "text_min": round(min(
        contrast(p[t], p[s_]) for t in texts for s_ in ("surface.void", "surface.field", "surface.panel")), 2)}
    if min(out["projector"]["edge"].values()) < dr["projector_edge_min"]:
        errs.append("V3T01: projector edge below the graphic minimum")
    dz = tok.get("depth", {})
    if dz and not (dz["ambient"] < dz["content"] < dz["relational"] < dz["focus"] < dz["context"] < dz["quarantine"]):
        errs.append("V3T09: depth order violates 05.5")
    if out["projector"]["text_min"] < tmin:
        errs.append("V3T01: projector text below 4.5")
    return out, errs


def color_report(tok: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    col, rules = resolve(tok), tok["contrast_rules"]
    out: dict[str, Any] = {"text": [], "tints": [], "pairs": []}
    errs = []
    for s in rules["text_surfaces"]:
        for t in rules["text_tokens"] + rules["text_tokens_field_panel"]:
            if t in rules["text_tokens_field_panel"] and s == "surface.elevated":
                continue
            c = round(contrast(col[t], col[s]), 2)
            out["text"].append([t, s, c])
            if c < rules["text_min"]:
                errs.append(f"TX23: {t} on {s} = {c} < {rules['text_min']}")
    for s in rules["tints"]:
        for t in rules["tint_text"]:
            c = round(contrast(col[t], col[s]), 2)
            out["tints"].append([t, s, c])
            if c < rules["text_min"]:
                errs.append(f"TX23: {t} on {s} = {c}")
    for a, b in combinations(rules["semantic"], 2):
        d = round(ciede2000(col[a], col[b]), 1)
        out["pairs"].append([a, b, d])
        if d < rules["semantic_pairs_delta_e_min"]:
            errs.append(f"TX23: ΔE00({a}, {b}) = {d} < {rules['semantic_pairs_delta_e_min']}")
    # decoration (DEC-xx) must never read as a sign, and text stays readable over the neural field (ADR-0007)
    out["decorative"], out["network"] = [], []
    for d_ in rules.get("decorative", []):
        for sem_ in rules["semantic"]:
            d = round(ciede2000(col[d_], col[sem_]), 1)
            out["decorative"].append([d_, sem_, d])
            if d < rules["decorative_delta_e_min"]:
                errs.append(f"TX23: decorative ΔE00({d_}, {sem_}) = {d} < {rules['decorative_delta_e_min']}")
        if "network_surface" in rules:
            a = float(tok["opacity"][rules["network_max_opacity"]])
            surf = col[rules["network_surface"]]
            mix = "#" + "".join(f"{round(int(surf[i:i + 2], 16) + a * (int(col[d_][i:i + 2], 16) - int(surf[i:i + 2], 16))):02X}"
                                for i in (1, 3, 5))
            for t in rules["text_tokens"] + rules["text_tokens_field_panel"]:
                c = round(contrast(col[t], mix), 2)
                out["network"].append([t, f"{rules['network_surface']} + {d_} @ {a}", c])
                if c < rules["text_min"]:
                    errs.append(f"TX23: {t} over neural field = {c} < {rules['text_min']}")
    for t in ["ink.secondary"] + rules["semantic"]:
        c = round(contrast(col[t], col["surface.field"]), 2)
        out["text"].append([t, "surface.field (graphic)", c])
        if c < rules["graphic_min"]:
            errs.append(f"TX23: graphic {t} = {c} < {rules['graphic_min']}")
    nrep, nerr = neuro_report(tok, col)
    out.update(nrep)
    return out, errs + nerr


# ---- generation --------------------------------------------------------------------------------------------------
def cssvar(name: str) -> str:
    return "--" + name.replace(".", "-")


def gen_tokens_css(tok: dict[str, Any]) -> str:
    L = [HEADER, ":root {"]
    for k, v in resolve(tok).items():
        L.append(f"  {cssvar('col.' + k)}: {v};")
    for k, v in tok["alias"].items():
        L.append(f"  {cssvar('col.' + k)}: var({cssvar('col.' + v)});")
    L.append(f"  --font-sans: '{tok['family']['sans']}', sans-serif;")
    L.append(f"  --font-mono: '{tok['family']['mono']}', monospace;")
    L.append("  --scale: 1;")
    for k, v in tok["type"].items():
        n = cssvar("type." + k)
        L += [f"  {n}-size: calc({v['size']}px * var(--scale));", f"  {n}-line: calc({v['line']}px * var(--scale));",
              f"  {n}-weight: {v['weight']};", f"  {n}-family: var(--font-{v['family']});",
              f"  {n}-tracking: {v.get('tracking', '0')};", f"  {n}-transform: {'uppercase' if v.get('caps') else 'none'};"]
    u = tok["space"]["unit"]
    for g in tok["space"]["grid"]:
        L.append(f"  --space-{g}: calc({g}px * var(--scale));")
    L.append(f"  --space-unit: calc({u}px * var(--scale));")
    for k, v in tok["border"].items():
        L.append(f"  {cssvar('border.' + k)}: {v}px;")
    for k, v in tok["radius"].items():
        L.append(f"  {cssvar('radius.' + k)}: {v}px;")
    for k, v in tok["pattern"].items():
        n = cssvar("pattern." + k)
        L += [f"  {n}-size: {v['size']}px;", f"  {n}-opacity: {v['opacity']};"]
    for k, v in tok["motion"].items():
        L.append(f"  {cssvar('motion.' + k)}: {v}ms;")
    for k, v in tok.get("opacity", {}).items():
        L.append(f"  {cssvar('opacity.' + k)}: {v};")
    for k, v in tok["line"].items():
        style, width, color = v.split()[:3]
        n = cssvar("line." + k)
        dash = {"solid": "none", "double": "none"}.get(style.split()[0], "")
        if style in ("dash", "dot"):
            dash = width.replace("/", " ")
            width = "1.5" if style == "dash" else "1.5"
            color = v.split()[2]
        L += [f"  {n}-width: {width};", f"  {n}-dash: {dash or 'none'};",
              f"  {n}-color: var({cssvar('col.' + color)});"]
    for k, v in tok["graph"].items():
        L.append(f"  {cssvar('graph.' + k)}: {v};")
    for k, v in tok["z"].items():
        L.append(f"  {cssvar('z.' + k)}: {v};")
    for k, v in tok["zone"].items():
        L.append(f"  {cssvar('zone.' + k)}: {v}px;")
    for group, prefix, unit in (("component", "cmp", "px"), ("decor", "decor", ""), ("comp", "comp", ""), ("light", "light", "px"), ("depth", "depth", ""), ("easing", "ease", "")):
        for k, v in tok.get(group, {}).items():
            L.append(f"  {cssvar(prefix + '.' + k)}: {v}{'' if k.endswith('alpha') else unit};")
    L.append("}")
    if tok.get("profile_projector"):
        L.append("html[data-profile='projector'] { " + " ".join(
            f"{cssvar('col.' + k) if not k.startswith('pattern.') else cssvar(k)}: {v};" for k, v in tok["profile_projector"].items()) + " }")
    L.append("[data-mode='presentation'] { --scale: %s; }" % tok["presentation_scale"])
    L.append("@media (prefers-reduced-motion: reduce) { :root { " +
             " ".join(f"{cssvar('motion.' + k)}: 0ms;" for k in tok["motion"]) + " } }")
    return "\n".join(L) + "\n"


def gen_tailwind(tok: dict[str, Any]) -> str:
    L = [HEADER, "@theme {", "  --color-*: initial;", "  --font-*: initial;", "  --spacing: var(--space-unit);"]
    for k in tok["color"]:
        L.append(f"  --color-{k.replace('.', '-')}: var({cssvar('col.' + k)});")
    for k in tok["alias"]:
        L.append(f"  --color-{k.replace('.', '-')}: var({cssvar('col.' + k)});")
    L += ["  --font-sans: var(--font-sans);", "  --font-mono: var(--font-mono);", "}"]
    return "\n".join(L) + "\n"


def ts_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def gen_sem_ts(doc: dict[str, Any], enums: dict[str, list[str]]) -> str:
    sems = doc["sems"]
    L = [HEADER, "export type SemId =", "  | " + "\n  | ".join(ts_str(s["id"]) for s in sems) + ";", ""]
    L.append("export interface SemEntry { id: SemId; name: string; shape: string; color: string; glyph: string | null;")
    L.append("  pattern: string | null; views: readonly number[]; primitive: string; term: string; exclusion: string }")
    L.append("export const SEM: Readonly<Record<SemId, SemEntry>> = {")
    for s in sems:
        c = s["channels"]
        L.append(f"  {ts_str(s['id'])}: {{ id: {ts_str(s['id'])}, name: {ts_str(s['name'])}, shape: {ts_str(c['shape'])}, "
                 f"color: {ts_str(c['color'])}, glyph: {ts_str(c['glyph']) if c['glyph'] else 'null'}, "
                 f"pattern: {ts_str(c['pattern']) if c['pattern'] else 'null'}, views: [{', '.join(map(str, s['views']))}], "
                 f"primitive: {ts_str(s['primitive'])}, term: {ts_str(s['term'])}, exclusion: {ts_str(s['exclusion'])} }},")
    L.append("};\n")
    for en in doc["signified_enums"]:
        vals = enums[en]
        m = {}
        for s in sems:
            for b in s["binds"]:
                if b.get("enum") == en:
                    for v in b["values"]:
                        m[v] = s["id"]
        signed = [v for v in vals if v in m]
        L.append(f"export const SEM_{en} = {{")
        for v in signed:
            L.append(f"  {ts_str(v)}: {ts_str(m[v])},")
        L.append(f"}} as const satisfies Record<{ ' | '.join(ts_str(v) for v in signed) }, SemId>;\n")
    flags = {b["flag"]: s["id"] for s in sems for b in s["binds"] if "flag" in b}
    types = {b["type"]: s["id"] for s in sems for b in s["binds"] if "type" in b}
    L.append("export const SEM_FLAG = {")
    for k, v in sorted(flags.items()):
        L.append(f"  {ts_str(k)}: {ts_str(v)},")
    L.append("} as const satisfies Record<string, SemId>;\n")
    L.append("export const SEM_TYPE = {")
    for k, v in sorted(types.items()):
        L.append(f"  {ts_str(k)}: {ts_str(v)},")
    L.append("} as const satisfies Record<string, SemId>;\n")
    L.append("export const SEM_BY_PRIMITIVE: Readonly<Record<string, readonly SemId[]>> = {")
    prim: dict[str, list[str]] = {}
    for s in sems:
        prim.setdefault(s["primitive"], []).append(s["id"])
    for k, v in sorted(prim.items()):
        L.append(f"  {ts_str(k)}: [{', '.join(ts_str(x) for x in v)}],")
    L.append("};\n")
    L.append("export const CANONICAL_GLYPH_TEST = " + ts_str("><≈→↔⊕⊖⊗⊘∆∇∑∂Σ") + ";")
    return "\n".join(L) + "\n"


def gen_terms_ts(t: dict[str, Any], enums: dict[str, list[str]], classified: list[str]) -> str:
    keys = [x["key"] for x in t["terms"]]
    L = [HEADER, "export type TermKey =", "  | " + "\n  | ".join(ts_str(k) for k in keys) + ";", "",
         "export type Lang = \"en\" | \"de\";",
         "export interface TermEntry { en: string; de: string; params: readonly string[] }",
         "export const TERMS: Readonly<Record<TermKey, TermEntry>> = {"]
    for x in t["terms"]:
        L.append(f"  {ts_str(x['key'])}: {{ en: {ts_str(x['en'])}, de: {ts_str(x['de'])}, params: [{', '.join(ts_str(p) for p in x.get('params', []))}] }},")
    L.append("};\n")
    for en in classified:
        vals = enums[en]
        L.append(f"export const TERM_{en} = {{")
        for v in vals:
            L.append(f"  {ts_str(v)}: {ts_str(t['enum_terms'][en][v])},")
        L.append(f"}} as const satisfies Record<{ ' | '.join(ts_str(v) for v in vals) }, TermKey>;\n")
    L.append("export const FORBIDDEN_VISIBLE: readonly string[] = [" + ", ".join(ts_str(x) for x in t["forbidden_visible"]) + "];")
    return "\n".join(L) + "\n"


def docs_register(doc: dict[str, Any]) -> str:
    L = ["# Semiontic register (generated)", "", "> Generated from `frontend/semiontics/cira.semiontics.yaml`. Do not edit.", "",
         "| SEM | Name | Shape | Colour | Glyph | Pattern | Bound states | Views | Primitive | TERM | Exclusion |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in doc["sems"]:
        c = s["channels"]
        b = "; ".join(f"{x.get('enum') or x.get('flag') or x.get('type')}" + (f"={'/'.join(x['values'])}" if 'values' in x else "")
                      for x in s["binds"]) or "—"
        L.append(f"| {s['id']} | {s['name']} | {c['shape']} | `{c['color']}` | {c['glyph'] or '—'} | {c['pattern'] or '—'} | {b} | "
                 f"{', '.join(map(str, s['views']))} | {s['primitive']} | `{s['term']}` | {s['exclusion']} |")
    if doc.get("decorative"):
        L += ["", "## Decoration (no sign)", "", "> Decorative elements carry no statement. They never use a sign colour, never "
              "carry `data-sem`, and stay below the text contrast limits (TX22, TX23).", "",
              "| DEC | Name | Where | Form | Meaning |", "|---|---|---|---|---|"]
        for d in doc["decorative"]:
            L.append(f"| {d['id']} | {d['name']} | {d['where']} | {d['form']} | {d['meaning']} |")
    return "\n".join(L) + "\n"


def docs_terms(t: dict[str, Any]) -> str:
    L = ["# Terminology (generated)", "", "> Generated from `frontend/semiontics/cira.terms.yaml`. Do not edit.", "",
         "| TERM | internal | EN | DE | meaning |", "|---|---|---|---|---|"]
    for x in t["terms"]:
        L.append(f"| `{x['key']}` | {x['internal'].replace('|', '/')} | {x['en'].replace('|', '/')} | {x['de'].replace('|', '/')} | {x['meaning'].replace('|', '/')} |")
    return "\n".join(L) + "\n"


def check(doc: dict[str, Any], terms: dict[str, Any], enums: dict[str, list[str]]) -> list[str]:
    deco_cols = set(doc["tokens"]["contrast_rules"].get("decorative", []))
    deco_errs = [f"TX22: {s['id']} uses decorative colour {s['channels']['color']}" for s in doc["sems"]
                 if s["channels"]["color"] in deco_cols]
    errs: list[str] = []
    errs += validate(doc, json.loads((SEMI / "semiontics.schema.json").read_text(encoding="utf-8")))
    errs += validate(terms, json.loads((SEMI / "terms.schema.json").read_text(encoding="utf-8")))
    classes = doc["signified_enums"] + doc["labelled_enums"] + doc["internal_enums"]
    for e in sorted(enums):
        if classes.count(e) != 1:
            errs.append(f"TX22: enum {e} classified {classes.count(e)}×")
    keys = [x["key"] for x in terms["terms"]]
    if len(set(keys)) != len(keys):
        errs.append("terms: duplicate keys")
    ks = set(keys)
    unsigned = doc.get("unsigned_values", {})
    for en in doc["signified_enums"]:
        for v in enums[en]:
            if v in unsigned.get(en, []):
                continue
            n = sum(1 for s in doc["sems"] for b in s["binds"] if b.get("enum") == en and v in b["values"])
            if n != 1:
                errs.append(f"TX22: {en}.{v} bound to {n} SEM")
    for en in doc["signified_enums"] + doc["labelled_enums"]:
        m = terms["enum_terms"].get(en, {})
        for v in enums[en]:
            if v not in m:
                errs.append(f"TX22: {en}.{v} without TERM")
            elif m[v] not in ks:
                errs.append(f"TX22: {en}.{v} → unknown TERM {m[v]}")
    for s in doc["sems"]:
        if s["term"] not in ks and not any(k.startswith(s["term"] + ".") for k in ks):
            errs.append(f"{s['id']}: TERM {s['term']} unknown")
        for b in s["binds"]:
            if "enum" in b:
                bad = set(b["values"]) - set(enums.get(b["enum"], []))
                if bad:
                    errs.append(f"{s['id']}: {b['enum']} has no values {sorted(bad)}")
    combos: dict[tuple[str, ...], str] = {}
    for s in doc["sems"]:
        c = s["channels"]
        k = (c["shape"], c["color"], str(c["glyph"]), str(c["pattern"]))
        if k in combos:
            errs.append(f"collision: {s['id']} and {combos[k]} share all channels {k}")
        combos[k] = s["id"]
    for x in terms["terms"]:
        for lang in ("en", "de"):
            for f in terms["forbidden_visible"]:
                if re.search(r"(?<![A-Za-z])" + re.escape(f) + r"(?![A-Za-z0-9])", x[lang]) and not x["key"].startswith("guard."):
                    errs.append(f"TX24: term {x['key']} ({lang}) contains forbidden '{f}'")
            for p in re.findall(r"\{(\w+)\}", x[lang]):
                if p not in x.get("params", []):
                    errs.append(f"terms: {x['key']} uses undeclared parameter {p}")
    _, cerr = color_report(doc["tokens"])
    return errs + cerr + deco_errs


def generate() -> dict[Path, str]:
    doc = yaml.safe_load((SEMI / "cira.semiontics.yaml").read_text(encoding="utf-8"))
    terms = yaml.safe_load((SEMI / "cira.terms.yaml").read_text(encoding="utf-8"))
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    enums = {k: v["enum"] for k, v in schema["$defs"].items() if "enum" in v}
    errs = check(doc, terms, enums)
    if errs:
        raise SystemExit("gen_semiontics: invalid SSOT\n  " + "\n  ".join(errs))
    rep, _ = color_report(doc["tokens"])
    classified = doc["signified_enums"] + doc["labelled_enums"]
    cases = {s["id"]: {"primitive": s["primitive"], "views": s["views"], "binds": s["binds"]} for s in doc["sems"]}
    return {
        ROOT / "frontend/src/semiontics/generated/tokens.css": gen_tokens_css(doc["tokens"]),
        ROOT / "frontend/src/semiontics/generated/tailwind.theme.css": gen_tailwind(doc["tokens"]),
        ROOT / "frontend/src/semiontics/generated/sem.ts": gen_sem_ts(doc, enums),
        ROOT / "frontend/src/semiontics/generated/tokens.ts": HEADER + "\n".join(
            f"export const {g.upper()} = {json.dumps({k.replace('.', '_'): v for k, v in doc['tokens'][g].items()}, sort_keys=True)} as const;"
            for g in ("graph", "zone", "z", "motion", "component", "decor", "comp", "light", "depth") if g in doc["tokens"]) + "\n",
        ROOT / "frontend/src/language/generated/terms.ts": gen_terms_ts(terms, enums, classified),
        ROOT / "frontend/test/generated/sem-cases.json": json.dumps(cases, ensure_ascii=False, indent=1) + "\n",
        ROOT / "docs/gui/semiontic-register.md": docs_register(doc),
        ROOT / "docs/gui/terminology.md": docs_terms(terms),
        ROOT / "docs/gui/color-report.json": json.dumps(rep, ensure_ascii=False, indent=1) + "\n",
    }


if __name__ == "__main__":
    files = generate()
    if "--check" in sys.argv:
        bad = [str(p.relative_to(ROOT)) for p, c in files.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
        print("semiontics: in sync" if not bad else f"semiontics: DRIFT {bad}")
        raise SystemExit(1 if bad else 0)
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c, encoding="utf-8")
    print(f"wrote {len(files)} generated files")
